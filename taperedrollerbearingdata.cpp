const QList<TaperedRollerBearingSpec> &TaperedRollerBearingTable::all() {
    static QList<TaperedRollerBearingSpec> list;
    if (list.isEmpty()) {
        const int n = int(sizeof(kRows) / sizeof(kRows[0]));
        for (int i = 0; i < n; ++i) {
            TaperedRollerBearingSpec s;
            s.name = QString::fromLatin1(kRows[i].name);
            s.d = kRows[i].d;
            s.D = kRows[i].D;
            s.B = kRows[i].B;
            s.T = kRows[i].T;
            s.C = kRows[i].C;
            s.r = kRows[i].r;
            s.R = kRows[i].R;
            list.append(s);
        }
    }
    return list;
}

TaperedRollerBearingSpec TaperedRollerBearingTable::find(const QString &name) {
    const QList<TaperedRollerBearingSpec> &list = all();
    for (int i = 0; i < list.size(); ++i) {
        if (list.at(i).name == name) return list.at(i);
    }
    return TaperedRollerBearingSpec();
}

QStringList TaperedRollerBearingTable::families() {
    return QStringList() << QStringLiteral("320") << QStringLiteral("302") << QStringLiteral("322")
                         << QStringLiteral("303") << QStringLiteral("323");
}

QString TaperedRollerBearingTable::familyOf(const QString &name) {
    return name.left(3);
}

QList<TaperedRollerBearingSpec> TaperedRollerBearingTable::byFamily(const QString &family) {
    QList<TaperedRollerBearingSpec> out;
    const QList<TaperedRollerBearingSpec> &list = all();
    for (int i = 0; i < list.size(); ++i) {
        if (familyOf(list.at(i).name) == family) out.append(list.at(i));
    }
    return out;
}

double TaperedRollerBearingTable::autoHatchScale(double d, double D) {
    // 컵·콘 단면 두께는 약 (D-d)/4 → 그 안에 해칭선 약 4줄
    const double thick = (D - d) * 0.25;
    if (thick <= 0.0) return 1.0;
    const double kAnsi31Spacing = 3.175;            // ANSI31 기본 선 간격 (스케일 1)
    double scale = (thick / 4.0) / kAnsi31Spacing;
    if (scale < 0.05) scale = 0.05;
    if (scale > 5.0)  scale = 5.0;
    return qRound(scale * 100.0) / 100.0;
}
