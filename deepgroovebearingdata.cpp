const QList<DeepGrooveBearingSpec> &DeepGrooveBearingTable::all() {
    static QList<DeepGrooveBearingSpec> list;
    if (list.isEmpty()) {
        const int n = int(sizeof(kRows) / sizeof(kRows[0]));
        for (int i = 0; i < n; ++i) {
            DeepGrooveBearingSpec s;
            s.name = QString::fromLatin1(kRows[i].name);
            s.d = kRows[i].d;
            s.D = kRows[i].D;
            s.B = kRows[i].B;
            s.r = kRows[i].r;
            list.append(s);
        }
    }
    return list;
}

double DeepGrooveBearingTable::autoHatchScale(double d, double D) {
    const double ringH = (D - d) * 0.5;
    if (ringH <= 0.0) return 1.0;
    const double kAnsi31Spacing = 3.175;            // ANSI31 기본 선 간격 (스케일 1)
    double scale = (ringH / 6.0) / kAnsi31Spacing;  // 링 높이 안에 해칭선 약 6줄
    if (scale < 0.05) scale = 0.05;
    if (scale > 5.0)  scale = 5.0;
    return qRound(scale * 100.0) / 100.0;
}

QStringList DeepGrooveBearingTable::families() {
    return QStringList() << QStringLiteral("60") << QStringLiteral("62") << QStringLiteral("63")
                         << QStringLiteral("64") << QStringLiteral("68") << QStringLiteral("69");
}

QString DeepGrooveBearingTable::familyOf(const QString &name) {
    // 앞 두 자리가 계열: 3자리(603→60, 623→62, 693→69), 4자리(6205→62)
    return name.left(2);
}

QList<DeepGrooveBearingSpec> DeepGrooveBearingTable::byFamily(const QString &family) {
    QList<DeepGrooveBearingSpec> out;
    const QList<DeepGrooveBearingSpec> &list = all();
    for (int i = 0; i < list.size(); ++i) {
        if (familyOf(list.at(i).name) == family) out.append(list.at(i));
    }
    return out;
}

DeepGrooveBearingSpec DeepGrooveBearingTable::find(const QString &name) {
    const QList<DeepGrooveBearingSpec> &list = all();
    for (int i = 0; i < list.size(); ++i) {
        if (list.at(i).name == name) return list.at(i);
    }
    return DeepGrooveBearingSpec();
}
